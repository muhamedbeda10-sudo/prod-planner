// Analyse the two factory samples, re-nest their parts and write every export
// to out/samples/. Run: npm run samples
//
// The samples are unitless ($INSUNITS = 0). Their extents (1210×2430 and
// 1220×2440 drawing units) match standard millimetre sheets, so this runner
// passes unit = mm EXPLICITLY — the same choice the screen asks a person for.

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { analyzeDxf } from "../src/engine/dxf/analyze";
import type { NestSettings } from "../src/engine/nesting/types";
import { partDxf } from "../src/engine/export/sheetExport";
import type { MachinesFile } from "../src/engine/machines/types";
import { partsFromAnalysis } from "../src/engine/parts";
import { runPipeline } from "./lib/runPipeline";

const root = fileURLToPath(new URL("..", import.meta.url));
const samplesDir = join(root, "samples");
const outRoot = join(root, "out", "samples");
const machines = JSON.parse(readFileSync(join(root, "config", "machines.local.json"), "utf8")) as MachinesFile;
const THICKNESS = 5; // the first file's name says 5mm; the second gives no thickness — 5 mm is an assumption for both, stated in the report

const files = readdirSync(samplesDir).filter((f) => f.toLowerCase().endsWith(".dxf")).sort();
// fixed ids and timestamps so a re-run with the same engine gives byte-identical files
const FIXED_AT = "2026-10-25T00:00:00.000Z";
const summary: string[] = ["# Sample runs", "", `Generated by \`npm run samples\` (deterministic: fixed run ids and timestamps; the commit date is the run date). Unit for both unitless files: **mm (chosen explicitly)**. Thickness assumed **${THICKNESS} mm** for both (only the first file name states it). The BOM column in the cut lists is the file name's first token, used as a label only.`, ""];
for (const f of files) {
  const path = join(samplesDir, f);
  const stem = basename(f, ".dxf").replace(/[^A-Za-z0-9._-]+/g, "_");
  const dir = join(outRoot, stem);
  mkdirSync(dir, { recursive: true });
  console.log(`\n==== ${f}`);
  const a = analyzeDxf(f, new Uint8Array(readFileSync(path)), { unit: "mm", thicknessMm: THICKNESS });
  const cls = a.classification!;
  const analysisOut = {
    file: a.fileName,
    bytes: a.bytes,
    acadVersion: a.acadVersion,
    units: a.units,
    extents: a.extents,
    layers: a.layers,
    entityCounts: a.entityCounts,
    extraction: a.extraction,
    topology: a.topology,
    kind: cls.kind,
    sheetSize: cls.sheetSize,
    pieces: cls.pieces.map((p) => ({ id: p.id, widthMm: p.bbox.maxX - p.bbox.minX, heightMm: p.bbox.maxY - p.bbox.minY, areaMm2: p.area, holes: p.holes.length, marks: p.marks.length, depth: p.depth, flags: p.flags, layers: p.outer.layers, at: { x: p.bbox.minX, y: p.bbox.minY } })),
    ignoredFaces: cls.ignoredFaces,
    partTypes: a.parts!.groups.map((g, i) => ({ id: `T${i + 1}`, instances: g.instances.map((x) => ({ piece: x.pieceId, rotationDeg: Math.round(x.transform.rotationDeg * 100) / 100, mirrored: x.transform.mirror })), mirrorOf: g.mirrorOf === null ? null : `T${g.mirrorOf + 1}`, representative: g.representative.id, flags: g.representative.flags })),
    warnings: a.warnings,
  };
  writeFileSync(join(dir, "analysis.json"), JSON.stringify(analysisOut, null, 2));
  console.log(`kind=${cls.kind} sheet=${cls.sheetSize?.w}×${cls.sheetSize?.h} pieces=${cls.pieces.length} types=${a.parts!.groups.length} ignored=${cls.ignoredFaces.length} parse+topology ${a.timings.totalMs.toFixed(0)} ms`);
  const { parts, skipped } = partsFromAnalysis(a, { bom: stem.split(/[-_ ]/)[0] });
  mkdirSync(join(dir, "parts"), { recursive: true });
  for (const p of parts) writeFileSync(join(dir, "parts", `${p.id}.dxf`), partDxf(p, `nesting-lab part ${p.id} from ${f} (${p.source?.geometryHash}) — units mm`));
  writeFileSync(join(dir, "parts", "skipped.json"), JSON.stringify(skipped, null, 2));
  const sheet = cls.sheetSize ?? { w: 1220, h: 2440 };
  const scenarios: { id: string; title: string; settings: NestSettings }[] = [
    { id: "A-spacing5-margin5", title: "5 mm spacing, 5 mm margin, 4 rotations", settings: { sheet: { widthMm: sheet.w, heightMm: sheet.h, quantity: null, material: "Steel", thicknessMm: THICKNESS, label: `${sheet.w}*${sheet.h}` }, spacingMm: 5, marginMm: 5, rotationsDeg: [0, 90, 180, 270], allowMirror: false, noGoZones: [], timeBudgetMs: 60_000 } },
    { id: "B-spacing2-margin2", title: "2 mm spacing, 2 mm margin, 4 rotations (closest to the original file's gaps)", settings: { sheet: { widthMm: sheet.w, heightMm: sheet.h, quantity: null, material: "Steel", thicknessMm: THICKNESS, label: `${sheet.w}*${sheet.h}` }, spacingMm: 2, marginMm: 2, rotationsDeg: [0, 90, 180, 270], allowMirror: false, noGoZones: [], timeBudgetMs: 60_000 } },
  ];
  summary.push(`## ${f}`, "", `- Kind: **${cls.kind}**, sheet boundary ${cls.sheetSize?.w} × ${cls.sheetSize?.h}, ${cls.pieces.length} pieces → ${a.parts!.groups.length} part types (${parts.reduce((n, p) => n + p.quantity, 0)} parts nested, ${skipped.length} types skipped: ${skipped.map((s) => `${s.id} — ${s.reason}`).join("; ") || "none"})`, `- Warnings: ${a.warnings.length}. (Timings vary by machine and are printed on the console, not kept here.)`, "");
  for (const sc of scenarios) {
    console.log(`-- scenario ${sc.id}`);
    const out = runPipeline(parts, sc.settings, join(dir, sc.id), machines, (m) => process.stdout.write(`\r${m}        `), { runId: `sample-${stem.slice(0, 11)}-${sc.id}`, createdAt: FIXED_AT, scrubTimings: true });
    const r = out.result;
    const v = out.report.verification!;
    const rt = out.report.roundTrip;
    console.log(`\n   ${r.sheets.length} sheets, utilization ${r.sheets.map((s) => (s.utilization * 100).toFixed(1) + "%").join(" / ")}, unplaced ${r.unplaced.reduce((n, u) => n + u.quantity, 0)}, nest ${r.timings.totalMs.toFixed(0)} ms (nfp ${r.stats.nfpMs} ms, booleans ${r.stats.booleanMs} ms), verify ${v.ok ? "OK" : "FAILED " + v.violations.length}, round-trip ${rt.every((x) => x.report.ok) ? "OK" : "FAILED"} (${rt.map((x) => `${x.report.matched}/${x.report.piecesExpected}`).join(", ")})`);
    summary.push(`### ${sc.id}: ${sc.title}`, "", `- Sheets: **${r.sheets.length}**; utilization per sheet: ${r.sheets.map((s) => (s.utilization * 100).toFixed(1) + "%").join(", ")}; unplaced: ${r.unplaced.reduce((n, u) => n + u.quantity, 0)}`, `- Strategy chosen: ${r.chosenStrategy.ordering} / ${r.chosenStrategy.objective}; NFPs computed ${r.stats.nfpComputed}, candidate positions ${r.stats.candidatesEvaluated}`, `- Verification: ${v.ok ? "passed" : "FAILED"} — ${v.stats.pairsChecked} pairs checked, min clearance ${v.stats.minClearanceMm?.toFixed(3) ?? "n/a"} mm, min edge distance ${v.stats.minEdgeDistanceMm?.toFixed(3)} mm`, `- DXF round-trip: ${rt.every((x) => x.report.ok) ? "passed" : "FAILED"} — ${rt.map((x) => `${x.fileName}: ${x.report.matched}/${x.report.piecesExpected} parts, max area Δ ${x.report.maxAreaDeltaMm2.toExponential(2)} mm², max box Δ ${x.report.maxBBoxDeltaMm.toExponential(2)} mm`).join("; ")}`, `- Files: ${out.files.map((p) => basename(p)).join(", ")}`, "");
    if (!v.ok) for (const x of v.violations.slice(0, 10)) summary.push(`  - ✗ ${x.message}`);
    for (const x of rt) if (!x.report.ok) for (const m of x.report.mismatches) summary.push(`  - ✗ ${x.fileName}: ${m}`);
  }
}
mkdirSync(outRoot, { recursive: true });
writeFileSync(join(outRoot, "SUMMARY.md"), summary.join("\n") + "\n");
console.log(`\nWrote ${join(outRoot, "SUMMARY.md")}`);
