// Writes lib/server/ai/schemaText.generated.ts — the database as the AI
// assistant is told about it (lib/domain/aiSchema.ts), out of
// prisma/schema.prisma. Run by the build, so a deployment always describes
// its own schema; run it after changing the schema (a test checks it).
//   npx tsx scripts/gen-ai-schema.ts
import { readFileSync, writeFileSync } from "node:fs";
import { aiSchemaText } from "../lib/domain/aiSchema";

const text = aiSchemaText(readFileSync("prisma/schema.prisma", "utf8"));
writeFileSync(
  "lib/server/ai/schemaText.generated.ts",
  `// Generated by scripts/gen-ai-schema.ts from prisma/schema.prisma — do not edit.\nexport const AI_SCHEMA_TEXT = ${JSON.stringify(text)};\n`,
);
console.log(`AI schema: ${text.length} characters`);
