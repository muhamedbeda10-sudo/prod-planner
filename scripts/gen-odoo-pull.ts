// Writes public/odoo-pull.js — the Odoo pull (lib/domain/odooPull.ts) bundled
// for the browser, served at /odoo-pull.js for the scheduled task to load into
// an Odoo page. Run it after changing the pull (a test checks it is current):
//   npx tsx scripts/gen-odoo-pull.ts
import { buildSync } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const ODOO_PULL_FILE = "public/odoo-pull.js";

export function buildOdooPull(): string {
  const r = buildSync({
    entryPoints: [fileURLToPath(new URL("./odoo-pull-entry.ts", import.meta.url))],
    bundle: true, minify: true, format: "iife", target: "es2020", write: false, legalComments: "none",
    banner: { js: "/* prod-planner Odoo pull — generated by scripts/gen-odoo-pull.ts from lib/domain/odooPull.ts; reads Odoo only. */" },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const js = buildOdooPull();
  writeFileSync(ODOO_PULL_FILE, js);
  console.log(`${ODOO_PULL_FILE}: ${js.length} characters`);
}
